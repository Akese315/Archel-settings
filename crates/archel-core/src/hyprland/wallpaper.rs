        let plan = plan_wallpaper_set(image.to_str().expect("utf-8")).expect("plan builds");
        let killed = Rc::new(Cell::new(false));
        let respawned = Rc::new(Cell::new(false));
        let kill_probe = Rc::clone(&killed);
        let respawn_probe = Rc::clone(&respawned);
        let report = apply_wallpaper_with(
            &base,
            &plan,
            || {
                kill_probe.set(true);
                Ok(())
            },
            || {
                respawn_probe.set(true);
                Ok(())
            },
        )
        .expect("injected lifecycle carries the apply");
        assert!(report.restarted);
        assert!(killed.get() && respawned.get(), "kill then respawn both ran");
