//! Desktop wallpaper via hyprpaper conf slice plus process restart
//! (APP-01, D-01).
//!
//! One mechanism only: the app-owned `archel-hyprpaper.conf` slice is
//! rewritten (backup-first, tmp+rename), the user `hyprpaper.conf`
//! gains one idempotent guarded `source = ...` line at END (last-wins
//! ordering), then `pkill -x hyprpaper` plus a detached respawn via
//! the `setsid` argv shim (no libc dep). There is deliberately NO
//! `hyprctl hyprpaper` path — hyprpaper 0.8.4 has no reload verb and
//! its IPC socket is off on the target machine (RESEARCH Pitfall 3) —
//! and the golden argv test below pins that absence structurally.
//!
//! Spawn discipline mirrors [`crate::proxy`]: which-gate, exact argv
//! never through a shell, `LC_ALL=C`, `wait_timeout` plus kill. Paths
//! validate BEFORE any spawn or write (canonicalize, must exist, must
//! be a regular image file by extension, barred characters rejected),
//! typed [`crate::ArchelError::DesktopInvalid`] naming the rejected
//! path (proxy.rs validator shape, `VpnPathInvalid` as the analog).

use serde::Serialize;

use super::{backup_before_write, hypr_dir};
use crate::error::ArchelError;
use crate::packages::QUERY_TIMEOUT;

/// App-owned hyprpaper slice filename inside the Hyprland config dir.
pub const SLICE_FILE: &str = "archel-hyprpaper.conf";
/// User-owned hyprpaper config (append-only source line, never rewritten).
pub const USER_CONF_FILE: &str = "hyprpaper.conf";
/// Image extensions hyprpaper loads (allowlist — anything else fails
/// typed before anything spawns or writes).
pub const IMAGE_EXTENSIONS: &[&str] = &["png", "jpg", "jpeg", "webp", "bmp", "gif"];

/// App-owned slice path under a Hyprland config dir.
pub fn slice_path_at(base: &std::path::Path) -> std::path::PathBuf {
    base.join(SLICE_FILE)
}

/// User-owned hyprpaper conf path under a Hyprland config dir.
pub fn user_conf_path_at(base: &std::path::Path) -> std::path::PathBuf {
    base.join(USER_CONF_FILE)
}

/// The guarded `source = ...` line for `base` (absolute slice path so
/// the daemon finds it regardless of working directory). Appended at
/// END of the user conf so app leaves win hyprlang last-wins ordering.
pub fn source_line_for(base: &std::path::Path) -> String {
    format!("source = {}", slice_path_at(base).display())
}

/// Validates one wallpaper candidate path BEFORE any spawn or write:
/// barred characters rejected first (quote, backslash, newline, NUL —
/// the value re-enters a conf file), then canonicalize (must exist),
/// must be a regular file, must carry an image extension, and must
/// not live under /proc, /sys, or /dev. Returns the canonical path.
pub fn validate_wallpaper_path(raw: &str) -> Result<std::path::PathBuf, ArchelError> {
    let trimmed = raw.trim();
    if trimmed.is_empty() {
        return Err(ArchelError::desktop_invalid("empty wallpaper path"));
    }
    if trimmed.contains(['"', '\\', '\n', '\r', '\0']) {
        return Err(ArchelError::desktop_invalid(format!(
            "rejected wallpaper path {trimmed:?}"
        )));
    }
    let canonical = std::fs::canonicalize(trimmed).map_err(|_| {
        ArchelError::desktop_invalid(format!("rejected wallpaper path {trimmed:?}"))
    })?;
    if !canonical.is_file() {
        return Err(ArchelError::desktop_invalid(format!(
            "rejected wallpaper path {trimmed:?}"
        )));
    }
    let under_sys = ["proc", "sys", "dev"].iter().any(|top| {
        canonical
            .components()
            .nth(1)
            .and_then(|c| c.as_os_str().to_str())
            == Some(top)
    });
    if under_sys {
        return Err(ArchelError::desktop_invalid(format!(
            "rejected wallpaper path {trimmed:?}"
        )));
    }
    let extension_ok = canonical
        .extension()
        .and_then(|ext| ext.to_str())
        .is_some_and(|ext| {
            IMAGE_EXTENSIONS.contains(&ext.to_lowercase().as_str())
        });
    if !extension_ok {
        return Err(ArchelError::desktop_invalid(format!(
            "rejected wallpaper path {trimmed:?}"
        )));
    }
    Ok(canonical)
}

/// Renders the app-owned hyprpaper slice for `path`: the verified
/// 0.8.x block syntax (empty monitor = all monitors, matching the
/// user's own conf style), `fit_mode = cover`. Pure and golden-tested.
pub fn render_hyprpaper_slice(path: &std::path::Path) -> String {
    format!(
        "# archel managed slice — regenerated by `archel`; edits inside are lost.\n\
         wallpaper {{\n\
         \x20   monitor =\n\
         \x20   path = {}\n\
         \x20   fit_mode = cover\n\
         }}\n",
        path.display()
    )
}

/// Parses the `path = ...` value back out of a slice body (pure over
/// the text so fixtures cover it without the filesystem).
pub fn parse_slice_path(text: &str) -> Option<String> {
    for line in text.lines() {
        let trimmed = line.trim();
        if let Some(rest) = trimmed.strip_prefix("path =") {
            let value = rest.trim().to_string();
            if !value.is_empty() {
                return Some(value);
            }
        }
    }
    None
}

/// Writes `body` to the app-owned slice atomically (tmp + rename),
/// with a timestamped backup first (Task-1 millis stamps).
pub fn write_slice_at(
    base: &std::path::Path,
    body: &str,
) -> Result<std::path::PathBuf, ArchelError> {
    let target = slice_path_at(base);
    backup_before_write(&target)?;
    let tmp = target.with_extension("tmp");
    std::fs::write(&tmp, body).map_err(|err| {
        ArchelError::Internal(format!("cannot write '{}': {err}", tmp.display()))
    })?;
    std::fs::rename(&tmp, &target).map_err(|err| {
        ArchelError::Internal(format!("cannot publish '{}': {err}", target.display()))
    })?;
    Ok(target)
}

/// Ensures the one-time guarded `source = ...` line at END of the user
/// hyprpaper conf (grep line equality before append — idempotent,
/// backup on first touch, tmp+rename publish). Refuses with typed
/// [`crate::ArchelError::HyprlandUnavailable`] when the user conf is
/// absent instead of planting a conf the daemon never reads (WR-06
/// analog). Returns true when appended, false when already present.
pub fn ensure_source_line_at(base: &std::path::Path) -> Result<bool, ArchelError> {
    let conf = user_conf_path_at(base);
    let current = std::fs::read_to_string(&conf).map_err(|err| {
        ArchelError::hyprland_unavailable(format!(
            "hyprpaper conf '{}' not present: {err}",
            conf.display()
        ))
    })?;
    let line = source_line_for(base);
    if current.lines().any(|existing| existing.trim() == line) {
        return Ok(false);
    }
    backup_before_write(&conf)?;
    let mut next = current;
    if !next.is_empty() && !next.ends_with('\n') {
        next.push('\n');
    }
    next.push_str(&line);
    next.push('\n');
    let tmp = conf.with_extension("tmp");
    std::fs::write(&tmp, next).map_err(|err| {
        ArchelError::Internal(format!("cannot write '{}': {err}", tmp.display()))
    })?;
    std::fs::rename(&tmp, &conf).map_err(|err| {
        ArchelError::Internal(format!("cannot publish '{}': {err}", conf.display()))
    })?;
    Ok(true)
}

/// Exact `pkill` argv ending the running hyprpaper daemon. Pure so the
/// golden test pins it without touching the process table.
pub fn pkill_argv() -> Vec<String> {
    vec!["pkill".to_string(), "-x".to_string(), "hyprpaper".to_string()]
}

/// Exact respawn argv for the detached daemon: the `setsid` shim when
/// present (verified live — util-linux on Arch), `nohup`-style only
/// when `setsid` is missing. Pure over the probe result so both shapes
/// stay golden-tested without spawning.
pub fn respawn_argv(setsid_available: bool) -> Vec<String> {
    if setsid_available {
        vec!["setsid".to_string(), "hyprpaper".to_string()]
    } else {
        vec!["nohup".to_string(), "hyprpaper".to_string()]
    }
}

/// Stops the running hyprpaper daemon (`pkill -x hyprpaper`):
/// which-gate, `LC_ALL=C`, `wait_timeout` plus kill. Exit 1 means "no
/// process matched" — nothing to stop, still Ok. Anything else fails
/// typed (the restart cannot proceed honestly).
pub fn kill_hyprpaper() -> Result<(), ArchelError> {
    kill_hyprpaper_with_tool("pkill")
}

/// Same as [`kill_hyprpaper`] but the binary name is injectable, so
/// the which-gate stays unit-coverable headless.
fn kill_hyprpaper_with_tool(tool: &str) -> Result<(), ArchelError> {
    let binary = which::which(tool)
        .map_err(|err| ArchelError::hyprland_unavailable(format!("{tool} ({err})")))?;
    let handle = duct::cmd(&binary, ["-x", "hyprpaper"])
        .unchecked()
        .env("LC_ALL", "C")
        .stdout_capture()
        .stderr_capture()
        .start()
        .map_err(|err| ArchelError::Internal(format!("cannot run '{tool}': {err}")))?;
    let output = match handle.wait_timeout(QUERY_TIMEOUT).map_err(|err| {
        ArchelError::Internal(format!("cannot wait on '{tool}': {err}"))
    })? {
        Some(output) => output.clone(),
        None => {
            let _ = handle.kill();
            return Err(ArchelError::hyprland_unavailable(format!(
                "'{tool}' exceeded the query timeout"
            )));
        }
    };
    match output.status.code() {
        Some(0) | Some(1) => Ok(()),
        code => Err(ArchelError::hyprland_unavailable(format!(
            "{tool} failed with exit code {code:?}"
        ))),
    }
}

/// Respawns hyprpaper detached after the conf write: the `setsid`
/// argv shim (stdio null, session env passthrough so the daemon joins
/// the live compositor — T-05-08), falling back to `nohup`-style only
/// when `setsid` is missing. Never waited on: the daemon outlives the
/// CLI by design.
pub fn respawn_hyprpaper() -> Result<(), ArchelError> {
    let signature = std::env::var_os("HYPRLAND_INSTANCE_SIGNATURE").ok_or_else(|| {
        ArchelError::hyprland_unavailable(
            "HYPRLAND_INSTANCE_SIGNATURE is unset (not running under Hyprland)",
        )
    })?;
    let argv = respawn_argv(which::which("setsid").is_ok());
    let binary = which::which(&argv[0])
        .map_err(|err| ArchelError::hyprland_unavailable(format!("{} ({err})", argv[0])))?;
    let mut cmd = duct::cmd(&binary, &argv[1..]);
    cmd = cmd
        .stdin_null()
        .stdout_null()
        .stderr_null()
        .env("LC_ALL", "C")
        .env("HYPRLAND_INSTANCE_SIGNATURE", &signature);
    if let Some(runtime) = std::env::var_os("XDG_RUNTIME_DIR") {
        cmd = cmd.env("XDG_RUNTIME_DIR", &runtime);
    }
    cmd.start()
        .map_err(|err| {
            ArchelError::hyprland_unavailable(format!("cannot respawn hyprpaper: {err}"))
        })?;
    Ok(())
}

/// A validated wallpaper transition: the canonical image path.
/// Planned read-only before any prompt — validation touches nothing
/// but the candidate path itself (canonicalize), never any config.
#[derive(Debug, Clone, PartialEq)]
pub struct WallpaperPlan {
    pub path: std::path::PathBuf,
}

/// Plans a wallpaper transition from one CLI path: validate first
/// (WR-02 — hostile input fails before any spawn, write, or prompt).
pub fn plan_wallpaper_set(raw: &str) -> Result<WallpaperPlan, ArchelError> {
    Ok(WallpaperPlan {
        path: validate_wallpaper_path(raw)?,
    })
}

/// The app slice state as one readout: the managed wallpaper path
/// (`None` when no slice was ever written). Serialized as-is for
/// `--json`.
#[derive(Debug, Clone, PartialEq, Serialize)]
pub struct WallpaperStatus {
    pub path: Option<String>,
}

/// Reads the current slice path (bare `archel appearance wallpaper`).
/// Read-only: no confirm, no write, user conf untouched.
pub fn read_wallpaper_at(base: &std::path::Path) -> WallpaperStatus {
    let path = std::fs::read_to_string(slice_path_at(base))
        .ok()
        .and_then(|body| parse_slice_path(&body));
    WallpaperStatus { path }
}

/// Outcome of a wallpaper mutation: the applied path plus the daemon
/// restart confirmation. Serialized as-is for `--json`.
#[derive(Debug, Clone, PartialEq, Serialize)]
pub struct WallpaperReport {
    pub path: String,
    pub restarted: bool,
}

/// Applies a wallpaper plan: slice rewrite (backup-first, atomic) plus
/// the idempotent source line, then daemon kill plus detached respawn
/// (D-01 one mechanism). Injectable lifecycle legs keep the
/// orchestration unit-coverable headless; production passes the real
/// `pkill`/`setsid` legs.
pub fn apply_wallpaper_with(
    base: &std::path::Path,
    plan: &WallpaperPlan,
    kill: impl FnOnce() -> Result<(), ArchelError>,
    respawn: impl FnOnce() -> Result<(), ArchelError>,
) -> Result<WallpaperReport, ArchelError> {
    write_slice_at(base, &render_hyprpaper_slice(&plan.path))?;
    ensure_source_line_at(base)?;
    kill()?;
    respawn()?;
    Ok(WallpaperReport {
        path: plan.path.to_string_lossy().into_owned(),
        restarted: true,
    })
}

/// Production leg: slice under `~/.config/hypr/`, real process table.
pub fn set_wallpaper(raw: &str) -> Result<WallpaperReport, ArchelError> {
    let base = hypr_dir();
    let plan = plan_wallpaper_set(raw)?;
    apply_wallpaper_with(&base, &plan, kill_hyprpaper, respawn_hyprpaper)
}

