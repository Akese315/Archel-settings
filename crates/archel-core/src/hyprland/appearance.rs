//! Window blur live-apply (APP-03 tracer).
//!
//! One path end-to-end: plan (pure) → snippet rewrite (durability,
//! backup + atomic) → `hyprctl eval 'hl.config({...})'` (liveness) →
//! `getoption -j` read-back (honest confirmation). Opacity leaves land
//! here in the expansion task; the snippet body composes every managed
//! leaf so later waves only extend [`AppearanceState`].

use serde::Serialize;

use super::{
    ensure_require_line_at, hypr_dir, parse_getoption_json, read_option,
    run_hyprctl, run_hyprctl_eval, snippet_path_at, write_snippet_at, OptionValue,
};
use crate::error::ArchelError;

/// Live option key for the blur switch (verified via getoption).
pub const BLUR_KEY: &str = "decoration:blur:enabled";

/// Every appearance leaf the app snippet manages. Later waves extend
/// this struct (opacity, font); the renderer below composes all of
/// them so the snippet stays one managed block.
#[derive(Debug, Clone, PartialEq, Serialize)]
pub struct AppearanceState {
    /// `decoration.blur.enabled` leaf.
    pub blur_enabled: bool,
    /// `decoration.active_opacity` leaf (expansion task owns writes).
    pub active_opacity: f64,
    /// `decoration.inactive_opacity` leaf (expansion task owns writes).
    pub inactive_opacity: f64,
}

impl Default for AppearanceState {
    fn default() -> Self {
        Self {
            blur_enabled: true,
            active_opacity: 1.0,
            inactive_opacity: 1.0,
        }
    }
}

/// Outcome of a blur/opacity mutation: the applied leaves plus the
/// read-back confirmation. Serialized as-is for `--json`.
#[derive(Debug, Clone, PartialEq, Serialize)]
pub struct AppearanceReport {
    pub blur_enabled: bool,
    pub active_opacity: f64,
    pub inactive_opacity: f64,
    /// Live read-back agreed with the applied value.
    pub read_back_ok: bool,
}

/// Renders the exact `hl.config` Lua statement for a blur switch.
/// Pure (golden-testable without spawning): machine-rendered bools
/// only, never interpolated user text.
pub fn blur_eval_statement(enabled: bool) -> String {
    format!("hl.config({{ decoration = {{ blur = {{ enabled = {enabled} }} }} }})")
}

/// Renders the managed snippet body for `state`: one `hl.config`
/// block naming every app-owned leaf. Line-level stable so later
/// upserts preserve sibling leaves.
pub fn render_snippet(state: &AppearanceState) -> String {
    format!(
        "-- archel managed block — regenerated by `archel`; edits inside are lost.\n\
         hl.config({{\n\
         \x20   decoration = {{ blur = {{ enabled = {} }}, active_opacity = {}, inactive_opacity = {} }},\n\
         }})\n",
        state.blur_enabled,
        super::appearance_float(state.active_opacity),
        super::appearance_float(state.inactive_opacity),
    )
}

/// Reads the current snippet state, falling back to defaults when the
/// snippet does not exist yet (first run). Never touches user files —
/// only the app-owned snippet is parsed.
pub fn current_snippet_state(
    base: &std::path::Path,
) -> Result<AppearanceState, ArchelError> {
    let path = snippet_path_at(base);
    let text = match std::fs::read_to_string(&path) {
        Ok(text) => text,
        Err(err) if err.kind() == std::io::ErrorKind::NotFound => {
            return Ok(AppearanceState::default());
        }
        Err(err) => {
            return Err(ArchelError::Internal(format!(
                "cannot read '{}': {err}",
                path.display()
            )));
        }
    };
    Ok(parse_snippet_state(&text))
}

/// Parses rendered leaf values back out of a managed block (pure over
/// the text so fixtures cover it without the filesystem).
fn parse_snippet_state(text: &str) -> AppearanceState {
    let mut state = AppearanceState::default();
    if text.contains("enabled = false") {
        state.blur_enabled = false;
    }
    for (marker, slot) in [
        ("active_opacity = ", &mut state.active_opacity),
        ("inactive_opacity = ", &mut state.inactive_opacity),
    ] {
        if let Some(rest) = text.find(marker).map(|i| &text[i + marker.len()..]) {
            let num: String = rest.chars().take_while(|c| c.is_ascii_digit() || *c == '.').collect();
            if let Ok(value) = num.parse::<f64>() {
                *slot = value;
            }
        }
    }
    state
}

/// Parses a `getoption decoration:blur:enabled -j` payload into the
/// live switch value. Pure for headless coverage.
pub fn parse_blur_enabled(out: &str) -> Result<bool, ArchelError> {
    match parse_getoption_json(out)? {
        OptionValue::Bool(value) => Ok(value),
        other => Err(ArchelError::hyprland_unavailable(format!(
            "unexpected blur option shape: {other:?}"
        ))),
    }
}

/// Applies a blur switch: snippet rewrite (durability) + `eval` live
/// leg + `getoption` read-back. The injectable `runner`/`reader` keep
/// the orchestration unit-coverable headless; production passes the
/// real `run_hyprctl` legs.
pub fn apply_blur_with(
    base: &std::path::Path,
    enabled: bool,
    runner: impl FnOnce(&str) -> Result<(), ArchelError>,
    reader: impl FnOnce() -> Result<bool, ArchelError>,
) -> Result<AppearanceReport, ArchelError> {
    let mut state = current_snippet_state(base)?;
    state.blur_enabled = enabled;
    write_snippet_at(base, &render_snippet(&state))?;
    ensure_require_line_at(base)?;
    runner(&blur_eval_statement(enabled))?;
    let live = reader()?;
    Ok(AppearanceReport {
        blur_enabled: enabled,
        active_opacity: state.active_opacity,
        inactive_opacity: state.inactive_opacity,
        read_back_ok: live == enabled,
    })
}

/// Production leg: snippet under `~/.config/hypr/`, real hyprctl.
pub fn set_blur(enabled: bool) -> Result<AppearanceReport, ArchelError> {
    let base = hypr_dir();
    apply_blur_with(
        &base,
        enabled,
        |lua| run_hyprctl_eval("hyprctl", lua),
        || read_option(BLUR_KEY).and_then(|value| match value {
            OptionValue::Bool(on) => Ok(on),
            other => Err(ArchelError::hyprland_unavailable(format!(
                "unexpected blur option shape: {other:?}"
            ))),
        }),
    )
}

/// Reads the live blur switch (honest read-back for bare invocations).
pub fn read_blur() -> Result<bool, ArchelError> {
    let out = run_hyprctl("hyprctl", &["getoption", BLUR_KEY, "-j"])?;
    parse_blur_enabled(&out)
}

/// French preview title (shown before `[o/N]`).
pub fn blur_preview_title() -> String {
    rust_i18n::t!("appearance.blur_preview_title").to_string()
}

/// French `(label, value)` preview rows.
pub fn blur_preview_rows(enabled: bool) -> Vec<(String, String)> {
    vec![(
        rust_i18n::t!("appearance.label_blur").to_string(),
        blur_word(enabled),
    )]
}

/// French confirmation prompt naming the target switch state.
pub fn confirm_blur_prompt(enabled: bool) -> String {
    rust_i18n::t!("appearance.confirm_blur", state = blur_word(enabled)).to_string()
}

/// French title for the post-apply report table.
pub fn blur_report_title() -> String {
    rust_i18n::t!("appearance.blur_report_title").to_string()
}

/// French rows for the post-apply report table.
pub fn blur_report_rows(report: &AppearanceReport) -> Vec<(String, String)> {
    vec![(
        rust_i18n::t!("appearance.label_blur").to_string(),
        blur_word(report.blur_enabled),
    )]
}

/// French ok line naming the applied switch state.
pub fn blur_ok_line(enabled: bool) -> String {
    rust_i18n::t!("appearance.blur_ok", state = blur_word(enabled)).to_string()
}

/// French wording for the blur switch (raw bool never renders).
fn blur_word(enabled: bool) -> String {
    if enabled {
        rust_i18n::t!("appearance.value_on").to_string()
    } else {
        rust_i18n::t!("appearance.value_off").to_string()
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn eval_statement_is_leaf_scoped_golden() {
        assert_eq!(
            blur_eval_statement(true),
            "hl.config({ decoration = { blur = { enabled = true } } })"
        );
        assert_eq!(
            blur_eval_statement(false),
            "hl.config({ decoration = { blur = { enabled = false } } })"
        );
        for stmt in [blur_eval_statement(true), blur_eval_statement(false)] {
            assert!(
                !stmt.contains("keyword") && !stmt.contains("reload"),
                "banned verbs must never shape apply argv: {stmt:?}"
            );
        }
    }

    #[test]
    fn blur_getoption_fixtures_parse() {
        assert_eq!(parse_blur_enabled(r#"{"bool": true, "set": true}"#), Ok(true));
        assert_eq!(
            parse_blur_enabled(r#"{"bool": false, "set": true}"#),
            Ok(false)
        );
        assert!(parse_blur_enabled(r#"{"float": 1.0, "set": true}"#.to_string().as_str()).is_err());
    }

    #[test]
    fn snippet_round_trips_blur_without_touching_siblings() {
        let body = render_snippet(&AppearanceState {
            blur_enabled: false,
            active_opacity: 0.9,
            inactive_opacity: 0.8,
        });
        let back = parse_snippet_state(&body);
        assert!(!back.blur_enabled);
        assert!((back.active_opacity - 0.9).abs() < f64::EPSILON);
        assert!((back.inactive_opacity - 0.8).abs() < f64::EPSILON);
        assert!(body.contains("-- archel managed block"));
    }

    #[test]
    fn apply_orchestration_writes_snippet_then_evals_then_reads_back() {
        use std::cell::RefCell;
        use std::rc::Rc;
        let base = std::env::temp_dir().join(format!(
            "archel-appearance-test-{}",
            std::process::id()
        ));
        let _ = std::fs::remove_dir_all(&base);
        std::fs::create_dir_all(&base).expect("scratch base must create");
        let ran = Rc::new(RefCell::new(String::new()));
        let probe = Rc::clone(&ran);
        let report = apply_blur_with(
            &base,
            false,
            |lua| {
                *probe.borrow_mut() = lua.to_string();
                Ok(())
            },
            || Ok(false),
        )
        .expect("injected legs must carry the apply");
        assert!(report.read_back_ok, "matching read-back confirms");
        assert_eq!(
            ran.borrow().as_str(),
            "hl.config({ decoration = { blur = { enabled = false } } })"
        );
        let snippet = std::fs::read_to_string(snippet_path_at(&base)).expect("snippet reads");
        assert!(snippet.contains("enabled = false"), "snippet persists the leaf");
        let mismatch = apply_blur_with(&base, true, |_| Ok(()), || Ok(false))
            .expect("read-back still reports");
        assert!(!mismatch.read_back_ok, "divergent read-back is honest, never ok");
        let _ = std::fs::remove_dir_all(&base);
    }

    #[test]
    fn apply_propagates_runner_failures_without_silent_ok() {
        let base = std::env::temp_dir().join(format!(
            "archel-appearance-fail-{}",
            std::process::id()
        ));
        let _ = std::fs::remove_dir_all(&base);
        std::fs::create_dir_all(&base).expect("scratch base must create");
        let err = apply_blur_with(
            &base,
            true,
            |_| Err(ArchelError::hyprland_unavailable("error: boom")),
            || Ok(true),
        )
        .expect_err("eval refusal must fail the apply");
        assert!(matches!(err, ArchelError::HyprlandUnavailable { .. }));
        let _ = std::fs::remove_dir_all(&base);
    }

    #[test]
    fn labels_come_from_the_catalog() {
        crate::i18n::set_language("fr");
        assert!(!blur_preview_title().is_empty());
        assert!(!confirm_blur_prompt(true).is_empty());
        assert!(!blur_ok_line(false).is_empty());
        assert!(!blur_report_title().is_empty());
    }
}
