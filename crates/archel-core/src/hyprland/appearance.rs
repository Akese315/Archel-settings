//! Window blur live-apply (APP-03 tracer).
//!
//! One path end-to-end: plan (pure) → snippet rewrite (durability,
//! backup + atomic) → `hyprctl eval 'hl.config({...})'` (liveness) →
//! `getoption -j` read-back (honest confirmation). Opacity leaves land
//! here in the expansion task; the snippet body composes every managed
//! leaf so later waves only extend [`AppearanceState`].

use serde::Serialize;

use super::{
    ensure_require_line_at, hypr_dir, parse_getoption_json, read_option, run_hyprctl,
    run_hyprctl_eval, snippet_path_at, write_snippet_at, OptionValue,
};
use crate::error::ArchelError;

/// Live option key for the blur switch (verified via getoption).
pub const BLUR_KEY: &str = "decoration:blur:enabled";
/// Live option keys for the opacity leaves (verified via getoption).
pub const ACTIVE_OPACITY_KEY: &str = "decoration:active_opacity";
/// Live option keys for the opacity leaves (verified via getoption).
pub const INACTIVE_OPACITY_KEY: &str = "decoration:inactive_opacity";

/// Every appearance leaf the app snippet manages. Later waves extend
/// this struct (font lives here since 05-02-01); the renderer below
/// composes all of them so the snippet stays one managed block.
#[derive(Debug, Clone, PartialEq, Serialize)]
pub struct AppearanceState {
    /// `decoration.blur.enabled` leaf.
    pub blur_enabled: bool,
    /// `decoration.active_opacity` leaf (expansion task owns writes).
    pub active_opacity: f64,
    /// `decoration.inactive_opacity` leaf (expansion task owns writes).
    pub inactive_opacity: f64,
    /// `misc.font_family` leaf (`None` renders no misc block, so
    /// pre-font snippets round-trip byte-identical).
    pub font_family: Option<String>,
}

impl Default for AppearanceState {
    fn default() -> Self {
        Self {
            blur_enabled: true,
            active_opacity: 1.0,
            inactive_opacity: 1.0,
            font_family: None,
        }
    }
}

/// Outcome of a blur/opacity mutation: the applied leaves plus the
/// read-back confirmation. Serialized as-is for `--json`.
#[derive(Debug, Clone, PartialEq, Serialize)]
pub struct AppearanceReport {
    pub blur_enabled: bool,
    pub active_opacity: f64,
    pub inactive_opacity: f64,
    /// Live read-back agreed with the applied value.
    pub read_back_ok: bool,
}

/// Renders the exact `hl.config` Lua statement for a blur switch.
/// Pure (golden-testable without spawning): machine-rendered bools
/// only, never interpolated user text.
pub fn blur_eval_statement(enabled: bool) -> String {
    format!("hl.config({{ decoration = {{ blur = {{ enabled = {enabled} }} }} }})")
}

/// Renders the managed snippet body for `state`: one `hl.config`
/// block naming every app-owned leaf. Line-level stable so later
/// upserts preserve sibling leaves. The `misc` line only renders
/// when a font was set through the font path (font families always
/// pass through `lua_quote` before reaching this text).
pub fn render_snippet(state: &AppearanceState) -> String {
    let mut out = format!(
        "-- archel managed block — regenerated by `archel`; edits inside are lost.\n\
         hl.config({{\n\
         \x20   decoration = {{ blur = {{ enabled = {} }}, active_opacity = {}, inactive_opacity = {} }},\n",
        state.blur_enabled,
        super::appearance_float(state.active_opacity),
        super::appearance_float(state.inactive_opacity),
    );
    if let Some(family) = state.font_family.as_deref() {
        let quoted = super::lua_quote(family).expect("font families validate before render");
        out.push_str(&format!("\x20   misc = {{ font_family = {quoted} }},\n"));
    }
    out.push_str("})\n");
    out
}

/// Reads the current snippet state, falling back to defaults when the
/// snippet does not exist yet (first run). Never touches user files —
/// only the app-owned snippet is parsed.
pub fn current_snippet_state(
    base: &std::path::Path,
) -> Result<AppearanceState, ArchelError> {
    let path = snippet_path_at(base);
    let text = match std::fs::read_to_string(&path) {
        Ok(text) => text,
        Err(err) if err.kind() == std::io::ErrorKind::NotFound => {
            return Ok(AppearanceState::default());
        }
        Err(err) => {
            return Err(ArchelError::Internal(format!(
                "cannot read '{}': {err}",
                path.display()
            )));
        }
    };
    Ok(parse_snippet_state(&text))
}

/// Parses rendered leaf values back out of a managed block (pure over
/// the text so fixtures cover it without the filesystem). Stored
/// families never contain quotes (the validator rejects them), so the
/// first closing quote ends the value.
fn parse_snippet_state(text: &str) -> AppearanceState {
    let mut state = AppearanceState::default();
    if text.contains("enabled = false") {
        state.blur_enabled = false;
    }
    for (marker, slot) in [
        ("active_opacity = ", &mut state.active_opacity),
        ("inactive_opacity = ", &mut state.inactive_opacity),
    ] {
        if let Some(rest) = text.find(marker).map(|i| &text[i + marker.len()..]) {
            let num: String = rest.chars().take_while(|c| c.is_ascii_digit() || *c == '.').collect();
            if let Ok(value) = num.parse::<f64>() {
                *slot = value;
            }
        }
    }
    if let Some(rest) = text
        .find("font_family = \"")
        .map(|i| &text[i + "font_family = \"".len()..])
    {
        let family: String = rest.chars().take_while(|c| *c != '"').collect();
        if !family.is_empty() {
            state.font_family = Some(family);
        }
    }
    state
}

/// Parses a `getoption decoration:blur:enabled -j` payload into the
/// live switch value. Pure for headless coverage.
pub fn parse_blur_enabled(out: &str) -> Result<bool, ArchelError> {
    match parse_getoption_json(out)? {
        OptionValue::Bool(value) => Ok(value),
        other => Err(ArchelError::hyprland_unavailable(format!(
            "unexpected blur option shape: {other:?}"
        ))),
    }
}

/// Applies a blur switch: `eval` live leg plus `getoption` read-back
/// FIRST, snippet persist only on read-back agreement (WR-01). A
/// refused eval or a disagreeing read-back returns `Err` with the
/// prior snippet body untouched — durable config can never claim a
/// value the compositor rejected. The injectable `runner`/`reader`
/// keep the orchestration unit-coverable headless; production passes
/// the real `run_hyprctl` legs.
pub fn apply_blur_with(
    base: &std::path::Path,
    enabled: bool,
    runner: impl FnOnce(&str) -> Result<(), ArchelError>,
    reader: impl FnOnce() -> Result<bool, ArchelError>,
) -> Result<AppearanceReport, ArchelError> {
    runner(&blur_eval_statement(enabled))?;
    let live = reader()?;
    if live != enabled {
        return Err(ArchelError::hyprland_unavailable(format!(
            "live read-back disagrees with the applied blur value"
        )));
    }
    let mut state = current_snippet_state(base)?;
    state.blur_enabled = enabled;
    write_snippet_at(base, &render_snippet(&state))?;
    ensure_require_line_at(base)?;
    Ok(AppearanceReport {
        blur_enabled: enabled,
        active_opacity: state.active_opacity,
        inactive_opacity: state.inactive_opacity,
        read_back_ok: true,
    })
}

/// Production leg: snippet under `~/.config/hypr/`, real hyprctl.
pub fn set_blur(enabled: bool) -> Result<AppearanceReport, ArchelError> {
    let base = hypr_dir();
    apply_blur_with(
        &base,
        enabled,
        |lua| run_hyprctl_eval("hyprctl", lua),
        || read_option(BLUR_KEY).and_then(|value| match value {
            OptionValue::Bool(on) => Ok(on),
            other => Err(ArchelError::hyprland_unavailable(format!(
                "unexpected blur option shape: {other:?}"
            ))),
        }),
    )
}

/// Reads the live blur switch (honest read-back for bare invocations).
pub fn read_blur() -> Result<bool, ArchelError> {
    let out = run_hyprctl("hyprctl", &["getoption", BLUR_KEY, "-j"])?;
    parse_blur_enabled(&out)
}

